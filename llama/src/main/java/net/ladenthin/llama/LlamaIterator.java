package net.ladenthin.llama;

import java.util.Iterator;
import java.util.NoSuchElementException;
import lombok.ToString;
import net.ladenthin.llama.json.CompletionResponseParser;
import net.ladenthin.llama.parameters.InferenceParameters;
import net.ladenthin.llama.value.LlamaOutput;

/**
 * This iterator is used by {@link LlamaModel#generate(InferenceParameters)} and
 * {@link LlamaModel#generateChat(InferenceParameters)}. In addition to implementing {@link Iterator},
 * it allows to cancel ongoing inference (see {@link #cancel()}).
 *
 * <p>{@link LlamaIterator} implements {@link AutoCloseable}. When used via {@link LlamaIterable}
 * inside a try-with-resources block, {@link #close()} is called automatically on early exit
 * (e.g. {@code break}), preventing the native task slot from leaking.
 *
 * <p>{@code toString} is generated by Lombok over the task id, the {@code hasNext}
 * flag, and the parser collaborator; the {@link LlamaModel} reference is excluded
 * because it would recursively dump the entire native model state.
 * {@code equals}/{@code hashCode} are intentionally NOT generated: iterators are
 * lifecycle handles tied to a single in-progress task, managed by identity.</p>
 */
@ToString
public final class LlamaIterator implements Iterator<LlamaOutput>, AutoCloseable {

    // Reference back to the owning LlamaModel — dumping it would recursively render
    // the entire native model state and produce log spam.
    @ToString.Exclude
    private final TaskSource model;

    private final int taskId;
    private final CompletionResponseParser completionParser = new CompletionResponseParser();

    // volatile: cancel() may be called from another thread, so the consuming thread
    // running next()/hasNext() must observe the flip without a data race.
    private volatile boolean hasNext = true;

    LlamaIterator(LlamaModel model, InferenceParameters parameters) {
        this(model, parameters, false);
    }

    LlamaIterator(LlamaModel model, InferenceParameters parameters, boolean chat) {
        this(TaskSource.of(model), parameters, chat);
    }

    /**
     * Creates an iterator over the given task source (tests use a fake one).
     *
     * @param model      the native task operations
     * @param parameters the inference parameters
     * @param chat       whether to start a chat completion instead of a raw completion
     */
    LlamaIterator(TaskSource model, InferenceParameters parameters, boolean chat) {
        this.model = model;
        // Pin the stream flag on a local derivation so the caller's parameters object
        // is not mutated — InferenceParameters is immutable and withStream returns a
        // new instance with the flag set.
        InferenceParameters streamingParams = parameters.withStream(true);
        // toJson(), never toString(): toString() is the redacted debug view and is deliberately
        // not valid JSON, so passing it here would send the native parser a body it rejects.
        taskId = chat
                ? model.requestChatCompletion(streamingParams.toJson())
                : model.requestCompletion(streamingParams.toJson());
    }

    @Override
    public boolean hasNext() {
        return hasNext;
    }

    @Override
    public LlamaOutput next() {
        if (!hasNext) {
            throw new NoSuchElementException();
        }
        String json = model.receiveCompletionJson(taskId);
        LlamaOutput output = completionParser.parse(json);
        // hasNext only ever goes from true to false. Writing !output.stop here would revive an
        // iterator that cancel() ended from another thread while this call waited for the result.
        if (output.stop) {
            hasNext = false;
            model.releaseTask(taskId);
        }
        return output;
    }

    /**
     * Cancel the ongoing generation process. Releases the native JNI reader for this task
     * so subsequent calls to {@link #next()} no longer return values.
     * <p>
     * Note: the underlying llama.cpp slot may continue running until its natural stop
     * condition, but the iterator stops yielding tokens immediately and the reader is
     * cleaned up. Safe to call multiple times.
     */
    public void cancel() {
        model.cancelCompletion(taskId);
        hasNext = false;
    }

    /**
     * Cancels any in-progress generation if the iterator has not yet reached a stop token.
     * Idempotent: subsequent calls are no-ops, and calling {@code close()} after natural
     * completion (the last {@link #next()} call returned a stop token) is also a no-op
     * because {@code releaseTask} was already invoked in {@link #next()}.
     *
     * <p>Prefer using the enclosing {@link LlamaIterable} in a try-with-resources block:
     * <pre>{@code
     * try (LlamaIterable it = model.generate(params)) {
     *     for (LlamaOutput out : it) {
     *         if (shouldStop(out)) break;
     *     }
     * }
     * }</pre>
     */
    @Override
    public void close() {
        if (hasNext) {
            cancel();
        }
    }

    /**
     * The native task operations this iterator drives. They are package-private natives of
     * {@link LlamaModel}; this seam exists so the iterator's handling of a concurrent
     * {@link #cancel()} can be tested without a loaded model.
     */
    interface TaskSource {
        /**
         * Starts a streamed raw completion.
         *
         * @param json the request body
         * @return the task id
         */
        int requestCompletion(String json);

        /**
         * Starts a streamed chat completion.
         *
         * @param json the request body
         * @return the task id
         */
        int requestChatCompletion(String json);

        /**
         * Waits for the next result of the task.
         *
         * @param taskId the task
         * @return the result as JSON
         */
        String receiveCompletionJson(int taskId);

        /**
         * Releases a task that has finished.
         *
         * @param taskId the task
         */
        void releaseTask(int taskId);

        /**
         * Releases a task that has not finished.
         *
         * @param taskId the task
         */
        void cancelCompletion(int taskId);

        /**
         * The task operations of a loaded model.
         *
         * @param model the model
         * @return its task operations
         */
        static TaskSource of(LlamaModel model) {
            return new TaskSource() {
                @Override
                public int requestCompletion(String json) {
                    return model.requestCompletion(json);
                }

                @Override
                public int requestChatCompletion(String json) {
                    return model.requestChatCompletion(json);
                }

                @Override
                public String receiveCompletionJson(int taskId) {
                    return model.receiveCompletionJson(taskId);
                }

                @Override
                public void releaseTask(int taskId) {
                    model.releaseTask(taskId);
                }

                @Override
                public void cancelCompletion(int taskId) {
                    model.cancelCompletion(taskId);
                }
            };
        }
    }
}
